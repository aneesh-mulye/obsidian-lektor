import esbuild from 'esbuild';
import { appendFileSync, existsSync, readFileSync, readdirSync } from 'node:fs';
import { builtinModules } from 'node:module';
import { join, resolve } from 'node:path';
import process from 'node:process';

const prod = process.argv[2] === 'production';

const banner = `/*
Lektor, an Obsidian plugin. Copyright (C) 2026 Aneesh Mulye.
Licensed under the GNU Affero General Public License, version 3 or later.
This file is generated by esbuild from the TypeScript sources; it bundles
third-party code whose licence notices are reproduced at the end of the file.
*/`;

/** Append the LICENSE file of every npm package that ended up in the bundle. */
/** Redirects markdown-it's `import * as mdurl from "mdurl"` (and only that one) to src/obsidian/ui/mdurl.ts. */
const markdownItMdurl = {
  name: 'lektor-markdown-it-mdurl',
  setup(build) {
    build.onResolve({ filter: /^mdurl$/ }, (args) => (/[\\/]node_modules[\\/]markdown-it[\\/]/.test(args.importer) ? { path: resolve('src/obsidian/ui/mdurl.ts') } : undefined));
  },
};

function appendThirdPartyLicences(metafile) {
  const packages = new Set();
  for (const input of Object.keys(metafile.inputs)) {
    const m = /(?:^|\/)node_modules\/((?:@[^/]+\/)?[^/]+)\//.exec(input);
    if (m) packages.add(m[1]);
  }
  let notices = '\n/*\nThird-party licences for code bundled in this file:\n';
  for (const pkg of [...packages].sort()) {
    const dir = join('node_modules', pkg);
    const { version, license } = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
    // LICENSE, LICENCE.md, LICENSE-MIT.txt, …
    const file = readdirSync(dir).find((f) => /^licen[cs]e([-.][\w.-]+)?$/i.test(f));
    if (!file || !existsSync(join(dir, file))) throw new Error(`No licence file found for bundled package ${pkg}`);
    const text = readFileSync(join(dir, file), 'utf8').replaceAll('*/', '* /');
    notices += `\n--- ${pkg}@${version} (${license}) ---\n\n${text.trim()}\n`;
  }
  appendFileSync('main.js', `${notices}*/\n`);
}

const context = await esbuild.context({
  banner: { js: banner },
  entryPoints: ['src/main.ts'],
  bundle: true,
  // markdown-it's punycode.js is replaced by a stand-in built on the URL parser (see the file).
  alias: { 'punycode.js': './src/obsidian/ui/punycode.ts' },
  // markdown-it's own import of mdurl gets Lektor's copy of its parse (src/obsidian/ui/mdurl.ts).
  plugins: [markdownItMdurl],
  external: [
    'obsidian',
    'electron',
    '@codemirror/*',
    '@lezer/*',
    ...builtinModules,
    ...builtinModules.map((m) => `node:${m}`),
  ],
  format: 'cjs',
  target: 'es2022',
  jsx: 'automatic',
  define: { 'process.env.NODE_ENV': JSON.stringify(prod ? 'production' : 'development') },
  logLevel: 'info',
  sourcemap: prod ? false : 'inline',
  treeShaking: true,
  minify: prod,
  legalComments: 'none', // full licence texts are appended instead
  metafile: true,
  outfile: 'main.js',
});

if (prod) {
  const result = await context.rebuild();
  appendThirdPartyLicences(result.metafile);
  await context.dispose();
} else {
  await context.watch();
}
